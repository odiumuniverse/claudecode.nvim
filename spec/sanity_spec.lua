describe("headless nvim", function()
  it("provides vim.text.diff", function()
    local indices = vim.text.diff("a\nb\n", "a\nc\n", { result_type = "indices" })
    assert.same({ { 2, 1, 2, 1 } }, indices)
  end)

  it("provides extmarks", function()
    local buf = vim.api.nvim_create_buf(false, true)
    vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "one", "two" })
    local ns = vim.api.nvim_create_namespace("claudecode_spec_sanity")
    local id = vim.api.nvim_buf_set_extmark(buf, ns, 1, 0, {})
    assert.same({ 1, 0 }, vim.api.nvim_buf_get_extmark_by_id(buf, ns, id, {}))
    vim.api.nvim_buf_delete(buf, { force = true })
  end)
end)
